"""prepare_geometry.py - build the real-ZCTA geometry sample for the rerun.

Downloads the U.S. Census Bureau 2024 Gazetteer ZCTA national file (public
domain) if it is not already present, then draws a seeded uniform random
sample of 1,500 ZCTA centroids. The sample is the ONLY real data used by the
rerun: every outcome remains synthetic, generated by the simulator.

Usage:  python prepare_geometry.py
Output: data/zcta_sample_1500.csv  (columns: zcta, lat, lon, aland_sqmi)
Seed:   20261021 (fixed; the draw is reproducible byte-for-byte given the
        same Gazetteer vintage).
"""
import io
import os
import urllib.request
import zipfile

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, "data")
URL = ("https://www2.census.gov/geo/docs/maps-data/data/gazetteer/"
       "2024_Gazetteer/2024_Gaz_zcta_national.zip")
TXT = os.path.join(DATA, "2024_Gaz_zcta_national.txt")
OUT = os.path.join(DATA, "zcta_sample_1500.csv")
SEED = 20261021
N_SAMPLE = 1500


def ensure_gazetteer():
    if os.path.exists(TXT):
        return
    os.makedirs(DATA, exist_ok=True)
    print("downloading", URL)
    raw = urllib.request.urlopen(URL, timeout=120).read()
    with zipfile.ZipFile(io.BytesIO(raw)) as zf:
        zf.extractall(DATA)
    print("extracted to", DATA)


def main():
    ensure_gazetteer()
    df = pd.read_csv(TXT, sep="\t", dtype={"GEOID": str})
    df.columns = [c.strip() for c in df.columns]
    df = df.rename(columns={"GEOID": "zcta", "INTPTLAT": "lat",
                            "INTPTLONG": "lon", "ALAND_SQMI": "aland_sqmi"})
    df = df[["zcta", "lat", "lon", "aland_sqmi"]].dropna()
    df["zcta"] = df["zcta"].str.strip().str.zfill(5)
    rng = np.random.default_rng(SEED)
    idx = np.sort(rng.choice(len(df), size=N_SAMPLE, replace=False))
    sample = df.iloc[idx].reset_index(drop=True)
    sample.to_csv(OUT, index=False)
    print(f"population ZCTAs: {len(df)}; sampled: {len(sample)} -> {OUT}")
    print(sample.describe().to_string())


if __name__ == "__main__":
    main()
